#!/usr/bin/env bash
# Who built this pull request — the one answer, used by the gate and by everything that routes to it.
#
# WHY THIS IS ITS OWN FILE. Independence was derived in three places and two of them disagreed. The
# gate read the pull request's own commit list; the routing read a merge-base range in a local clone.
# Those are different sets of commits, so a reviewer was told it was independent, posted a verdict,
# and had to withdraw it when the gate refused. **A routing rule that does not match the gate sends
# roles to do work that will not be accepted**, which is worse than sending them nowhere. One
# derivation, one answer, three callers.
#
# AN ARCHIVE COMMIT DOES NOT MAKE YOU AN AUTHOR, AND THE DIFF DECIDES THAT — NEVER THE SUBJECT LINE.
#
# The product role must commit `openspec archive` onto the branch before merging: the generated-files
# gate refuses a hand-edited spec, and archiving after the merge leaves main claiming a change is in
# flight that has already shipped. So product ends up an author of every feature pull request, and
# after that only qa can certify one. Measured: eleven pull requests, eight red for want of a verdict,
# and exactly one role in the whole process eligible to give it. A single point of failure by
# construction, and it failed.
#
# Independence exists so that nobody certifies their own judgement about the product. An archive
# commit carries no such judgement — it is generated by a command, it touches nothing but
# `openspec/`, and a second gate already refuses it if it was hand-authored. It cannot hide the kind
# of defect a review is for.
#
# **SO THE EXEMPTION IS EARNED BY THE DIFF: a commit is spec-only when it changes no path outside
# `openspec/`.** A subject line is a claim; a diff is a fact. Exempting `chore(...): archive ...` by
# its message would let any agent carry code through the one gate in this process that is not
# mechanical, simply by naming a commit after a thing it is not. There is no version of that worth
# the convenience.
#
# Usage: pr-authors.sh --pr <n> [role]            # from the API — what the routing uses
#        pr-authors.sh --range <base> <head> [role]  # from this clone — what the gate uses
#        pr-authors.sh ... --all-trailers            # every trailer, exemption NOT applied
#        pr-authors.sh --is-spec-only < filelist     # the predicate alone, for driving it directly
#        pr-authors.sh --self-test
#
# AN EMPTY AUTHOR SET HAS TWO MEANINGS AND THEY ARE NOT THE SAME FACT.
#
#   no `Agent:` trailer on any commit   → who built this CANNOT BE DETERMINED. A defect in the
#                                         commits; the naming gate reports it with its remedy.
#   trailers present, all spec-only     → DETERMINED: nobody authored product judgement here, so
#                                         every role is independent and any of them may review.
#
# AND A THIRD FACT IS NOT AN EMPTY AUTHOR SET AT ALL — IT IS EXIT 3 (Issue #79). Both meanings above
# are answers. When `--pr` cannot reach the API the question was not answered, and the two are not
# interchangeable: `--pr` printed nothing and exited 0 under a secondary rate limit, the queue read
# that as "nobody built it, so every role is independent", and offered a pull request carrying nine
# `Agent: dev` trailers to dev. The gate re-derives authorship from git at verdict time, where the
# lookup does not fail, so it saw `dev` and refused the review dev had just done.
#
#   0  → the answer follows on stdout (possibly empty, and that emptiness is DETERMINED)
#   1  → role query only: that role authored nothing here
#   2  → usage
#   3  → COULD NOT DETERMINE. Not an author set. Independence cannot be established in either
#        direction, so a caller must stop rather than route on it.
#
# `--range` reads this clone and has no such failure mode; its exit codes are unchanged, which is
# why `check-review.sh` — the only `--range` caller — needs no change to go with this.
#
# The first build of the exemption collapsed those into one empty list, and a pull request whose only
# commit was an archive — #63, a real one — was refused with "no commit carries an Agent: trailer"
# about a commit that carries `Agent: product`. It could not be merged except with `--admin`. That is
# this project's signature defect, introduced into the gate that exists to police it, by the change
# that was meant to remove a different instance of it. `--all-trailers` is how a caller tells them
# apart, and every caller must.
#
# With no role: prints every author, one per line. With a role: exits 0 if that role authored
# something here (i.e. is NOT independent), 1 if it did not.
set -euo pipefail

RAW=0
args=()
for a in "$@"; do
  case "$a" in --all-trailers) RAW=1 ;; *) args+=("$a") ;; esac
done
[ "${#args[@]}" -gt 0 ] && set -- "${args[@]}"

case "${1:-}" in
  --pr|--range|--self-test|--is-spec-only) : ;;
  *) echo "::error::usage: pr-authors.sh --pr <n> [role] | --range <base> <head> [role] [--all-trailers] | --is-spec-only | --self-test" >&2; exit 2 ;;
esac

resolve_repo() {
  [ -n "${REPO:-}" ] && return 0
  local url; url=$(git config --get remote.origin.url 2>/dev/null || echo "")
  [ -n "$url" ] && REPO=$(printf '%s' "$url" | sed -E 's#^(https://[^/]+/|git@[^:]+:)##; s#\.git$##')
  [ -n "${REPO:-}" ] || { echo "::error::no repository: no 'origin' remote here. Set REPO." >&2; exit 2; }
}

# THE ONE DECISION, AND EVERY CALLER REACHES IT. Takes a newline-separated file list; answers whether
# this commit can make somebody an author. Empty list means a commit that changed nothing — a merge,
# usually — and those carry no authorship either.
# BLANK LINES ARE NOT PATHS. `git show --name-only --format=""` emits a leading empty line on some
# git versions and not others — 2.54 on the runner does, 2.50.1 on a laptop does not. An empty line
# does not match `^openspec/`, so `grep -v` selected it, so an archive commit touching nothing but
# openspec/ conferred authorship after all — **on the runner only**. A reviewer was cleared as
# independent by the local answer, did the review, and had the gate refuse the verdict it had just
# posted. One blank line, and the two halves of "one derivation, one answer" disagreed.
is_spec_only() { # is_spec_only <<< "<files>"
  local files
  files=$(grep -v '^[[:space:]]*$' || true)
  [ -n "$files" ] || return 0
  ! printf '%s\n' "$files" | grep -qv '^openspec/'
}

# The trailer, which is what the naming gate requires of every commit and what the review gate reads.
trailer_of() { sed -n 's/^Agent:[[:space:]]*//p' | head -1; }

authors_from_pr() {
  local num=$1 shas sha msg role files
  resolve_repo
  # ROLE BY ROLE, STOPPING AT THE FIRST COMMIT THAT MAKES IT AN AUTHOR. The naive shape fetches the
  # file list of every commit of every open pull request, which on a real board is hundreds of calls
  # a round for a queue that is supposed to be cheap enough to run constantly. A role needs one
  # non-spec-only commit to be an author, so the search can stop there — and the answer is identical.
  # A THIRD MEANING, AND IT IS NOT AN EMPTY AUTHOR SET (Issue #79). The two documented above are
  # both DETERMINED answers. This one is not: the call failed, so who built this was not computed.
  # `2>/dev/null || echo ""` collapsed it into the determined pair, and under a secondary rate limit
  # — which fails intermittently — the queue then offered a pull request to the role that wrote it.
  # EXIT 3, not 0-with-nothing and not 2 (a usage error): a caller must be able to tell "could not
  # ask" from "asked, and nobody is an author".
  # STDERR TO A FILE, NOT MERGED INTO THE VALUE. `2>&1` would fold any warning gh prints on a
  # SUCCESSFUL call into the commit list, and a warning is not a sha.
  local errf; errf=$(mktemp); trap 'rm -f "$errf"' RETURN
  shas=$(gh api "repos/$REPO/pulls/$num/commits" --paginate \
         --jq '.[] | "\(.sha)\t\((.commit.message | split("\n") | map(select(startswith("Agent:"))) | .[0]) // "")"' 2>"$errf") || {
    echo "::error::the commit list of pull request $num could not be read, so who built it CANNOT BE DETERMINED: $(tr '\n' ' ' < "$errf")" >&2
    echo "  This is a LOOKUP FAILURE and NOT a statement that nobody authored it. Independence" >&2
    echo "  cannot be established from it, in either direction." >&2
    return 3
  }
  [ -n "$shas" ] || return 0
  local roles r
  roles=$(printf '%s\n' "$shas" | cut -f2 | sed 's/^Agent:[[:space:]]*//' | grep -v '^$' | sort -u || true)
  for r in $roles; do
    while IFS=$'\t' read -r sha msg; do
      [ -n "$sha" ] || continue
      [ "$(printf '%s' "$msg" | sed 's/^Agent:[[:space:]]*//')" = "$r" ] || continue
      if [ "$RAW" = 1 ]; then echo "$r"; break; fi
      # AN UNREADABLE DIFF IS NOT A DIFF THAT TOUCHED NOTHING (Issue #79). `is_spec_only` answers 0
      # for an empty file list, which is correct for a commit that changed nothing and catastrophic
      # for a commit whose file list could not be fetched: the author of a code commit silently
      # became independent of it. The exemption is earned by the diff, so no diff means no answer.
      files=$(gh api "repos/$REPO/commits/$sha" --jq '.files[]?.filename' 2>"$errf") || {
        echo "::error::the file list of commit $sha could not be read, so whether it is spec-only CANNOT BE DETERMINED: $(tr '\n' ' ' < "$errf")" >&2
        echo "  The exemption is earned by the diff. Without the diff there is no answer, and an" >&2
        echo "  absent answer must not be read as 'this commit confers no authorship'." >&2
        return 3
      }
      if ! printf '%s' "$files" | is_spec_only; then echo "$r"; break; fi
    done < <(printf '%s\n' "$shas")
  done
}

authors_from_range() {
  local base=$1 head=$2 sha role files
  # `--no-merges`: a merge commit carries no trailer and introduces no change of its own. It is also
  # how another branch's archive commit arrives here, which is a second way product became the author
  # of a pull request it had never touched.
  for sha in $(git log --no-merges --format=%H "$base..$head" 2>/dev/null); do
    role=$(git log -1 --format=%B "$sha" | trailer_of)
    [ -n "$role" ] || continue
    # PLUMBING, NOT PORCELAIN. `git show --name-only --format=""` is formatted for people and its
    # blank lines move between versions; `diff-tree` is plumbing and its output is stable, which is
    # the property this comparison needs. The predicate strips blanks anyway — both, because either
    # alone would have been enough to prevent the outage and neither alone is obviously sufficient
    # for the next version of git.
    if [ "$RAW" = 1 ]; then echo "$role"; continue; fi
    files=$(git diff-tree --no-commit-id --name-only -r "$sha" 2>/dev/null || echo "")
    printf '%s' "$files" | is_spec_only || echo "$role"
  done | sort -u
}

self_test() {
  local rc=0 tmp out base head me
  # ABSOLUTE, RESOLVED BEFORE ANYTHING cd's. Every arm below runs from inside the fixture directory,
  # and a relative BASH_SOURCE resolves to nothing there — the whole self-test died with 127 and no
  # output, which is a self-test that cannot fail rather than one that passed.
  me=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/$(basename "${BASH_SOURCE[0]}")
  tmp=$(mktemp -d); trap 'rm -rf "$tmp"' RETURN
  git -C "$tmp" init -q -b main
  git -C "$tmp" config user.email t@t; git -C "$tmp" config user.name t
  mkdir -p "$tmp/openspec/specs/x" "$tmp/internal"
  echo seed > "$tmp/f"; git -C "$tmp" add -A; git -C "$tmp" commit -qm "chore: seed"
  base=$(git -C "$tmp" rev-parse HEAD)

  echo code > "$tmp/internal/a.go"; git -C "$tmp" add -A
  git -C "$tmp" commit -qm "feat(x): the work

Agent: dev"

  echo spec > "$tmp/openspec/specs/x/spec.md"; git -C "$tmp" add -A
  git -C "$tmp" commit -qm "chore(x): archive the change

Agent: product"
  head=$(git -C "$tmp" rev-parse HEAD)

  # 1. A SPEC-ONLY COMMIT MUST NOT MAKE ITS AUTHOR AN AUTHOR. This is the deadlock: product archives
  #    every feature, so without this qa is the only role that can ever certify one.
  out=$( cd "$tmp" && bash "$me" --range "$base" "$head" 2>&1 )
  case "$out" in
    *product*) echo "SELF-TEST FAIL: an archive commit touching only openspec/ still made product an author — qa remains the only possible reviewer of every feature" >&2; rc=1 ;;
  esac
  # 2. AND THE ROLE THAT WROTE CODE MUST STILL BE ONE. An exemption that swallows everything is not
  #    an exemption, and it would disable the only non-mechanical gate in this process.
  case "$out" in
    *dev*) : ;;
    *) echo "SELF-TEST FAIL: the role that wrote the code was not reported as an author (got: '$out')" >&2; rc=1 ;;
  esac

  # 3. THE EXEMPTION MUST BE EARNED BY THE DIFF, NOT CLAIMED BY THE SUBJECT. **This is the arm that
  #    matters.** A commit named like an archive that also carries code must still make its author an
  #    author — otherwise any agent walks code past the review gate by choosing a commit message,
  #    and the gate is decoration.
  echo more > "$tmp/openspec/specs/x/spec.md"; echo sneak > "$tmp/internal/b.go"
  git -C "$tmp" add -A
  git -C "$tmp" commit -qm "chore(x): archive the change

Agent: product"
  head=$(git -C "$tmp" rev-parse HEAD)
  out=$( cd "$tmp" && bash "$me" --range "$base" "$head" 2>&1 )
  case "$out" in
    *product*) : ;;
    *) echo "SELF-TEST FAIL: a commit named 'archive' that also changed internal/b.go did NOT make its author an author — code walks past the review gate on a subject line (got: '$out')" >&2; rc=1 ;;
  esac

  # 4. THE ROLE QUERY MUST AGREE WITH THE LIST, since callers use one or the other and a disagreement
  #    between them is the same drift this file exists to end.
  ( cd "$tmp" && bash "$me" --range "$base" "$head" dev ) \
    || { echo "SELF-TEST FAIL: 'dev' is an author but the role query said it was not" >&2; rc=1; }
  echo spec2 > "$tmp/openspec/specs/x/other.md"; git -C "$tmp" add -A
  git -C "$tmp" commit -qm "chore(x): archive another

Agent: qa"
  head=$(git -C "$tmp" rev-parse HEAD)
  ( cd "$tmp" && bash "$me" --range "$base" "$head" qa ) \
    && { echo "SELF-TEST FAIL: qa's only commit was spec-only, so it must remain independent" >&2; rc=1; }

  # 5. A MERGE COMMIT CARRIES NO AUTHORSHIP. It is how another branch's archive commit arrives on a
  #    pull request its owner never touched — measured on a real board, and the route by which
  #    product became the author of work it had not done.
  git -C "$tmp" checkout -q -b side "$base"
  # `base` predates openspec/specs/x/, so the directory has to be recreated on this branch.
  mkdir -p "$tmp/openspec/specs/x"
  echo o > "$tmp/openspec/specs/x/side.md"; git -C "$tmp" add -A
  git -C "$tmp" commit -qm "chore(y): archive elsewhere

Agent: ops"
  git -C "$tmp" checkout -q main
  git -C "$tmp" merge -q --no-ff side -m "Merge side" 2>/dev/null || true
  head=$(git -C "$tmp" rev-parse HEAD)
  out=$( cd "$tmp" && bash "$me" --range "$base" "$head" 2>&1 )
  case "$out" in
    *ops*) echo "SELF-TEST FAIL: a spec-only commit inherited through a merge made its author an author here" >&2; rc=1 ;;
  esac

  # THE PREDICATE, DRIVEN AGAINST LITERAL FILE LISTS RATHER THAN AGAINST WHATEVER THE LOCAL GIT
  # EMITS. This is #61's criterion 6 and the reason that outage was invisible: every arm above builds
  # its fixture with the same git whose output shape is the variable, so it agrees with itself on
  # every machine and disagreed with the runner on one. These are the shapes git 2.54 and git 2.50.1
  # produce, written down, so a change in either is caught here instead of in a withdrawn review.
  local case_in case_want got_rc
  while IFS='|' read -r case_in case_want; do
    [ -n "$case_in" ] || continue
    got_rc=0; printf "$case_in" | bash "$me" --is-spec-only || got_rc=$?
    [ "$got_rc" = "$case_want" ] || {
      echo "SELF-TEST FAIL: is_spec_only on $(printf '%q' "$case_in") gave rc=$got_rc, wanted $case_want" >&2; rc=1; }
  done <<'CASES'
openspec/a.md\n|0
\nopenspec/a.md\n|0
openspec/a.md\n\n|0
\n\nopenspec/a.md\nopenspec/b.md\n|0
internal/a.go\n|1
\ninternal/a.go\n|1
\nopenspec/a.md\ninternal/a.go\n|1
\n|0
CASES

  # AN EMPTY AUTHOR SET HAS TWO MEANINGS, AND `--all-trailers` IS HOW A CALLER TELLS THEM APART.
  # Without this, a pull request whose only commit is an archive is refused as though its commits
  # carried no trailer at all — which is what happened to #63, and it could not be merged.
  local tmp2 b2 h2
  tmp2=$(mktemp -d)
  git -C "$tmp2" init -q -b main
  git -C "$tmp2" config user.email t@t; git -C "$tmp2" config user.name t
  mkdir -p "$tmp2/openspec/specs/x"
  echo s > "$tmp2/f"; git -C "$tmp2" add -A; git -C "$tmp2" commit -qm "chore: seed"
  b2=$(git -C "$tmp2" rev-parse HEAD)
  echo spec > "$tmp2/openspec/specs/x/spec.md"; git -C "$tmp2" add -A
  git -C "$tmp2" commit -qm "chore(x): archive only

Agent: product"
  h2=$(git -C "$tmp2" rev-parse HEAD)
  out=$( cd "$tmp2" && bash "$me" --range "$b2" "$h2" 2>&1 )
  [ -z "$out" ] || { echo "SELF-TEST FAIL: an archive-only branch reported an author ('$out') — nobody authored product judgement there" >&2; rc=1; }
  out=$( cd "$tmp2" && bash "$me" --range "$b2" "$h2" --all-trailers 2>&1 )
  case "$out" in
    *product*) : ;;
    *) echo "SELF-TEST FAIL: --all-trailers lost the trailer that is actually there — the caller cannot tell 'nobody is an author' from 'the commits carry no trailer', which is how #63 became unmergeable" >&2; rc=1 ;;
  esac
  # AND A BRANCH WITH NO TRAILER AT ALL MUST REPORT NOTHING FROM BOTH, or the distinction is a
  # difference in name only.
  echo more > "$tmp2/openspec/specs/x/spec.md"; git -C "$tmp2" add -A
  git -C "$tmp2" commit -qm "chore(x): no trailer here"
  out=$( cd "$tmp2" && bash "$me" --range "$h2" "$(git -C "$tmp2" rev-parse HEAD)" --all-trailers 2>&1 )
  [ -z "$out" ] || { echo "SELF-TEST FAIL: --all-trailers invented a trailer for a commit that has none (got '$out')" >&2; rc=1; }
  rm -rf "$tmp2"

  # AND A LOOKUP THAT COULD NOT ANSWER IS NEITHER OF THOSE EMPTY SETS (Issue #79). Driven through
  # the real `--pr` entry point against a stub `gh` that fails, because the defect was not in the
  # logic — every line did what it said — it was that the failure was converted to an empty set at
  # the boundary, and no arm here asked what `--pr` does when the API is unreachable.
  local stub prc
  stub=$(mktemp -d)
  printf '#!/usr/bin/env bash\necho "You have exceeded a secondary rate limit" >&2\nexit 1\n' > "$stub/gh"
  chmod +x "$stub/gh"
  prc=0
  ( PATH="$stub:$PATH" REPO=x/y bash "$me" --pr 1 ) >/dev/null 2>&1 || prc=$?
  [ "$prc" -eq 3 ] || {
    echo "SELF-TEST FAIL: --pr exited $prc when the API could not be reached, not 3. A caller cannot tell 'could not determine who built this' from 'determined that nobody did', and the queue then offers a pull request to the role that wrote it" >&2; rc=1; }
  # THE ROLE QUERY MUST NOT ANSWER EITHER. `--pr 1 dev` exits 1 for "dev authored nothing here", and
  # a failed lookup borrowing that code tells a role it is independent of work it wrote.
  prc=0
  ( PATH="$stub:$PATH" REPO=x/y bash "$me" --pr 1 dev ) >/dev/null 2>&1 || prc=$?
  [ "$prc" -eq 3 ] || {
    echo "SELF-TEST FAIL: the role query exited $prc under a failed lookup, not 3 — 1 means 'not an author', which is an answer nothing computed" >&2; rc=1; }
  # AND --all-trailers TOO, or the fix is applied to one of a pair and the caller that reads both
  # still cannot tell an outage from a determined answer.
  prc=0
  ( PATH="$stub:$PATH" REPO=x/y bash "$me" --pr 1 --all-trailers ) >/dev/null 2>&1 || prc=$?
  [ "$prc" -eq 3 ] || {
    echo "SELF-TEST FAIL: --all-trailers exited $prc under a failed lookup, not 3" >&2; rc=1; }
  rm -rf "$stub"

  [ "$rc" -eq 0 ] && echo "self-test passed: a spec-only commit confers no authorship, a code commit does, a commit NAMED archive that carries code still does, the role query agrees with the list, and an inherited commit does not; blank lines cannot change the predicate, an archive-only branch is distinguishable from one with no trailers, and a lookup that could not answer exits 3 rather than reporting an empty author set"
  return $rc
}

[ "$1" = "--self-test" ] && { self_test; exit $?; }
# THE PREDICATE, DRIVABLE WITHOUT GIT. #61's criterion: a self-test that builds its fixtures with the
# tool under test cannot observe that tool changing. This entry point takes a file list as text, so
# the shapes git emits can be asserted as literals rather than reproduced by the local git.
[ "$1" = "--is-spec-only" ] && { is_spec_only; exit $?; }

case "$1" in
  # `|| exit $?` IS THE WHOLE POINT AND IT IS NOT DECORATION (Issue #79). A command substitution is a
  # subshell: without this the function's `return 3` sets `$?` on an assignment `set -e` does not
  # abort on in every bash, `all` becomes empty, and the outage renders as a determined empty author
  # set — the exact collapse this file's header forbids, reintroduced by the shape of the call.
  --pr)    all=$(authors_from_pr "${2:?pull request number}") || exit $?; want=${3:-} ;;
  --range) all=$(authors_from_range "${2:?base}" "${3:?head}"); want=${4:-} ;;
esac
all=$(printf '%s\n' "$all" | grep -v '^$' | sort -u || true)

if [ -n "${want:-}" ]; then
  printf '%s\n' "$all" | grep -qx "$want"
  exit $?
fi
printf '%s\n' "$all" | grep -v '^$' || true
